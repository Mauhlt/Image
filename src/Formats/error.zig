    // ── signature / structure ──
    UnexpectedSignature,
    InvalidHeader,
    InvalidHeaderLen,
    InvalidMarker,
    InvalidEndMarker,
    InvalidChunkHeader,
    InvalidChunkTag,
    InvalidChunkLen,
    InvalidChunkOrder,
    InvalidCrc,
    InvalidToken,
    MissingIhdr,
    MissingIdat,
    MissingIend,
    MissingFrame,
    MissingScan,
    MissingHuffmanTable,
    MissingQuantTable,

    // ── data / sizes ──
    UnexpectedEndOfData,
    InvalidDataLen,
    InvalidDataOffset,
    InvalidDimensions,
    InvalidNumOfPixels,
    InvalidNum,
    InvalidMaxVal,
    InvalidRLEData,
    InvalidHuffmanCode,
    InvalidNumberOfColors,
    InvalidImportantColors,
    InvalidComponentCount,
    InvalidTransform,
    InvalidColorCacheIndex,
    InvalidBackReference,
    DecompressionFailed,
    Overflow,
    OutOfBounds,

    // ── unsupported features ──
    InvalidBitsPerPixel,
    InvalidCompression,
    InvalidColorspace,
    InvalidChannels,
    UnsupportedBitsPerPixel,
    UnsupportedColorspace,
    UnsupportedCompression,
    UnsupportedDepth,
    UnsupportedFilterMethod,
    UnsupportedGamma,
    UnsupportedInterlaceMethod,
    UnsupportedType,
    UnsupportedSrgb,
    UnsupportedFeature,
    UnsupportedProgressive,
    UnsupportedLossy,
    UnsupportedHeader,
    UnsupportedPixels,
};
